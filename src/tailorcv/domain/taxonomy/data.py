def _validate_families(families: tuple[Family, ...]) -> None:
    family_keys = [family.key for family in families]
    specialty_keys = [item.key for family in families for item in family.specialties]
    if len(set(family_keys)) != len(family_keys):
        raise ValueError("role-family keys must be unique")
    if len(set(specialty_keys)) != len(specialty_keys):
        raise ValueError("specialty keys must be unique")
    for family in families:
        _validate_family_evidence(family)


def _validate_family_evidence(family: Family) -> None:
    if family.sector not in SECTORS:
        raise ValueError(f"unknown role-family sector: {family.sector}")
    if not family.titles or not family.terms:
        raise ValueError(f"role family must carry title and body evidence: {family.key}")
    normalized_titles = [title.casefold().strip() for title in family.titles]
    if len(set(normalized_titles)) != len(normalized_titles):
        raise ValueError(f"duplicate title evidence in role family: {family.key}")
    if _GENERIC_OCCUPATION_TITLES & set(normalized_titles):
        raise ValueError(f"generic title cannot establish a role family: {family.key}")


_validate_families(FAMILIES)
