"""The shipped role-family and specialty vocabulary.

This is data, shipped as a typed Python table. A term here is a phrase, never a
bare noun: "pipeline" is a sales word and a data word, so the table carries
"sales pipeline" and "data pipeline" and neither carries "pipeline".
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Specialty:
    """A narrower reading inside a family, named only when the text earns it."""

    key: str
    label: str
    terms: tuple[str, ...]


@dataclass(frozen=True)
class Family:
    """One role family: what it is called, and the language that evidences it.

    ``titles`` are phrases from a job title and are weighted above body language,
    because a title is the posting's own name for the work. ``terms`` are
    compound phrases from the body. Neither list is exhaustive; the reading
    abstains when the evidence is thin.
    """

    key: str
    label: str
    sector: str
    titles: tuple[str, ...]
    terms: tuple[str, ...]
    specialties: tuple[Specialty, ...] = ()


